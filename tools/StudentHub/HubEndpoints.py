def counts():
    from collections import Counter
    c = Counter(k for _, _, k, _, _ in REST_ENDPOINTS)
    return {"rest": len(REST_ENDPOINTS), "ws": len(WS_ROUTES),
            "read": c.get("read", 0), "write": c.get("write", 0)}


def is_write(path, method="GET"):
    """学社端写判定（与 xmyz 的 endpoint_kind.is_write 无关、语义相反：
    这里返回 True 表示会改动数据，供测试与文档统计，不做拦截）。
    同一路径可挂多种方法（GET/PUT /admin/banners），按 (method, path) 判。"""
    for m, p, k, _, _ in REST_ENDPOINTS:
        if p == path and m == method:
            return k == "write"
    raise KeyError("未注册端点: %s %s" % (method, path))
